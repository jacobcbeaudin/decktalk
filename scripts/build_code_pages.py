"""Generate one docs page per error code and per finding code, from the enums that declare them.

    uv run scripts/build_code_pages.py --write    # write every page
    uv run scripts/build_code_pages.py --check    # exit 1 if a committed page would change

Every error block and every finding line prints a docs URL, so the page for a code lands with the
code and resolves from the first run. The sentence, the severity, the exit code and the settings
keys a code depends on come from the enum member and from the keys that name it, so a page cannot
say something the code does not.

Every page ends with what to do: the code's own remedy, and a link to each troubleshooting section
the troubleshooting page's symptom table sends that code to, read off that table so the two pages
cannot point different ways.

It also writes the table of the codes the page raises into the runtime reference, between two
markers, because a table typed by hand drifts from the pages this script writes.
"""

from __future__ import annotations

import json
import re
import sys
from functools import cache
from pathlib import Path

import generated
from decktalk.cli import catalog
from decktalk.errors import ErrorCode
from decktalk.findings import REPORTED_WHEN, Code, RaisedBy, Severity

ROOT = Path(__file__).resolve().parent.parent

RUNTIME = ROOT / "docs" / "reference" / "runtime.mdx"
TROUBLESHOOTING = ROOT / "docs" / "help" / "troubleshooting.mdx"
SYMPTOMS = "## From a symptom to a code"
"""The heading of the troubleshooting table whose rows send each code to the section that covers it."""
NOT_A_CODE = ("When the answer is not a code", "when-the-answer-is-not-a-code")
"""The troubleshooting section a code no symptom row lists is sent to, which covers the event stream and -v."""
ROW_SECTION = re.compile(r"\[([^\]]+)\]\(#([a-z0-9-]+)\)\s*\|\s*$")
"""The last cell of a symptom row, which links the section that says what to do."""
ERRORS = ROOT / "docs" / "reference" / "errors"
FINDINGS = ROOT / "docs" / "reference" / "findings"
GENERATED = "{/* Generated by scripts/build_code_pages.py from the enums in src/decktalk. Do not edit by hand. */}"
TABLE = ("{/* page codes: generated by scripts/build_code_pages.py */}", "{/* end page codes */}")
"""The markers around the runtime reference's code table, which is the one part of that page written here."""

SEVERITY = {Severity.ERROR: "an error", Severity.WARNING: "a warning"}
"""Each severity as a page sentence says it, with its article."""


def page(title: str, description: str, body: list[str]) -> str:
    """One docs page as it is committed, which is the frontmatter, the notice and the rows.

    The description is a code's sentence, which may hold a colon, so it is written as a quoted string,
    which YAML reads back as the sentence whatever it holds.
    """
    lines = ["---", f"title: {title}", f"description: {json.dumps(description)}", "---", "", GENERATED, "", *body]
    return "\n".join(lines).rstrip() + "\n"


@cache
def symptom_rows() -> tuple[str, ...]:
    """The rows of the troubleshooting page's symptom table, each a line of the table as written."""
    text = TROUBLESHOOTING.read_text(encoding="utf-8")
    _, _, after = text.partition(SYMPTOMS)
    table = after.split("\n## ", 1)[0]
    return tuple(line for line in table.splitlines() if line.startswith("| ") and ROW_SECTION.search(line))


def troubleshooting(code: Code | ErrorCode) -> list[tuple[str, str]]:
    """Each troubleshooting section a symptom row sends this code to, as its title and anchor, in table order."""
    kind = "findings" if isinstance(code, Code) else "errors"
    link = f"(/reference/{kind}/{code.value})"
    sections: list[tuple[str, str]] = []
    for row in symptom_rows():
        found = ROW_SECTION.search(row)
        if found and link in row and found.groups() not in sections:
            sections.append((found[1], found[2]))
    return sections


def what_to_do(code: Code | ErrorCode) -> list[str]:
    """The closing section of a code's page: its remedy, then where troubleshooting says more."""
    sections = troubleshooting(code) or [NOT_A_CODE]
    links = [f"[{title}](/help/troubleshooting#{anchor})" for title, anchor in sections]
    *before, last = links
    named = f"{', '.join(before)} and {last}" if before else last
    return ["", "## What to do", "", code.remedy, "", f"Troubleshooting says more under {named}."]


def error_page(code: ErrorCode) -> str:
    """The page for one error code, which is what the printed error block links to."""
    return page(
        title=code.value,
        description=code.sentence,
        body=[
            code.sentence,
            "",
            f"A command that ends this way exits {code.exit_code}. The JSON object carries `error.code` of",
            f"`{code.value}` and one sentence in `error.message`. `error.hint` carries the next step when",
            "DeckTalk knows one, and is null when it does not.",
            *what_to_do(code),
        ],
    )


def reported(code: Code) -> str:
    """The sentence naming each command that reports a code and when, the first with the verb and the rest after it."""
    if not code.raised_in:
        return "No command reports it, so only the page's own console says it."
    first, *rest = code.raised_in
    clauses = [f"`decktalk {first}` reports it {REPORTED_WHEN[first]}"]
    clauses += [f"`decktalk {command}` {REPORTED_WHEN[command]}" for command in rest]
    *before, last = clauses
    return f"{', '.join(before)}, and {last}." if before else f"{last}."


def finding_page(code: Code) -> str:
    """The page for one finding code, which is what the printed finding line links to."""
    decides = ", ".join(f"`{key}`" for key in catalog.deciding(code))
    body = [
        code.sentence,
        "",
        f"This finding is {SEVERITY[code.severity]}, and {code.raised_by.sentence}. {reported(code)}",
        f"Pass `--allow {code.value}` to carry on past it, and `--fail-on` to choose which severity fails a run.",
    ]
    if decides:
        body += ["", f"The settings that move this verdict are {decides}."]
    body += what_to_do(code)
    return page(title=code.value, description=code.sentence, body=body)


def documents() -> dict[Path, str]:
    """Every page this generator owns, and the runtime reference with its table of the codes the page raises."""
    pages = {ERRORS / f"{code.value}.mdx": error_page(code) for code in ErrorCode}
    pages |= {FINDINGS / f"{code.value}.mdx": finding_page(code) for code in Code}
    rows = ["| Code | What the page could not honour |", "|---|---|"]
    rows += [f"| `{code.value}` | {code.sentence} |" for code in Code if code.raised_by is RaisedBy.RUNTIME]
    table = "\n".join(["", "", *rows, "", ""])
    pages[RUNTIME] = generated.splice(RUNTIME.read_text(encoding="utf-8"), TABLE, table, where=RUNTIME)
    return pages


if __name__ == "__main__":
    sys.exit(generated.run(documents, owned=[ERRORS / "*.mdx", FINDINGS / "*.mdx"]))
